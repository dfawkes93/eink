#!/usr/bin/env python3
"""Renders a TrueType font into an epdiy / LilyGo-EPD47 GFXfont header.

Same output format as the library's scripts/fontconvert.py (4-bit grey, two
pixels per byte, zlib-compressed glyphs, printable ASCII only), so the
generated fonts work with the library's write_mode()/get_text_bounds().

    uv run --no-project --with freetype-py python tools/make_font.py \
        RobotoBold18 18 Roboto-Bold.ttf > src/fonts/robotobold18.h
"""
import argparse
import math
import sys
import zlib

import freetype

FIRST, LAST = 32, 126  # the board's fonts are ASCII-only
DPI = 150              # what the library's own fonts were rendered at


def floor26(v):
    return int(math.floor(v / 64))


def ceil26(v):
    return int(math.ceil(v / 64))


def pack(bitmap):
    """8-bit coverage -> 4-bit, low nibble first, each row padded to a byte."""
    out = bytearray()
    buf = bitmap.buffer
    for row in range(bitmap.rows):
        line = buf[row * bitmap.pitch: row * bitmap.pitch + bitmap.width]
        for x in range(0, bitmap.width, 2):
            lo = line[x] >> 4
            hi = (line[x + 1] & 0xF0) if x + 1 < bitmap.width else 0
            out.append(lo | hi)
    return bytes(out)


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("name", help="C identifier of the font, e.g. RobotoBold18")
    p.add_argument("size", type=int, help="size in points")
    p.add_argument("ttf")
    args = p.parse_args()

    face = freetype.Face(args.ttf)
    face.set_char_size(args.size << 6, args.size << 6, DPI, DPI)

    data, glyphs = bytearray(), []
    for cp in range(FIRST, LAST + 1):
        index = face.get_char_index(cp)
        if index == 0 and cp != 32:
            sys.exit(f"{args.ttf} has no glyph for {chr(cp)!r}")
        face.load_glyph(index, freetype.FT_LOAD_RENDER)
        g = face.glyph
        blob = zlib.compress(pack(g.bitmap))
        glyphs.append((g.bitmap.width, g.bitmap.rows, floor26(g.advance.x),
                       g.bitmap_left, g.bitmap_top, len(blob), len(data), cp))
        data += blob

    n = args.name
    out = ["#pragma once", '#include "epd_driver.h"',
           f"// Generated by tools/make_font.py from {args.ttf.rsplit('/', 1)[-1]} at {args.size} pt.",
           f"const uint8_t {n}Bitmaps[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        out.append("    " + " ".join(f"0x{b:02X}," for b in data[i:i + 16]))
    out.append("};")
    out.append(f"const GFXglyph {n}Glyphs[] = {{")
    for *props, cp in glyphs:
        label = "<backslash>" if cp == 92 else chr(cp)
        out.append("    { " + ", ".join(str(v) for v in props) + f" }}, // {label}")
    out.append("};")
    out.append(f"const UnicodeInterval {n}Intervals[] = {{")
    out.append(f"    {{ 0x{FIRST:X}, 0x{LAST:X}, 0x0 }},")
    out.append("};")
    out += [f"const GFXfont {n} = {{",
            f"    (uint8_t*){n}Bitmaps,",
            f"    (GFXglyph*){n}Glyphs,",
            f"    (UnicodeInterval*){n}Intervals,",
            "    1,",
            "    1,",
            f"    {ceil26(face.size.height)},",
            f"    {ceil26(face.size.ascender)},",
            f"    {floor26(face.size.descender)},",
            "};"]
    print("\n".join(out))


if __name__ == "__main__":
    main()
